def read_json(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def require(record, keys, label):
    if not isinstance(record, dict):
        raise TypeError(f"{label}: expected an object")
    for key in keys:
        if key not in record:
            raise ValueError(f"{label}: missing {key}")


def local_link(path, label, output):
    relative = os.path.relpath(ROOT / path, (ROOT / output).parent).replace("\\", "/")
    return f"[{label}]({relative.replace(' ', '%20')})"


def header(title, sources, output):
    links = " · ".join(local_link(path, "원본", output) for path in sources)
    return [
        f"# {title}",
        "",
        f"<!-- Generated by tools/project_docs.py. Sources: {', '.join(sources)} -->",
        f"{links}에서 생성한 프로젝션입니다. 변경은 원본에 반영한 뒤 `uv run --no-project python tools/project_docs.py`로 재생성합니다.",
        "",
    ]


def row(values):
    return (
        "| "
        + " | ".join(
            str(value).replace("|", "\\|").replace("\n", " ") for value in values
        )
        + " |"
    )


def table(headings, rows):
    return [
        row(headings),
        row(["---"] * len(headings)),
        *[row(values) for values in rows],
        "",
    ]


def task_rows(tasks, output):
    rows = []
    for path, task in tasks:
        owner = task.get("owner") or (
            task["suggested_owner"] + " (제안)"
            if task.get("suggested_owner")
            else "미정"
        )
        rows.append(
            (
                local_link(path, task["id"], output),
                task.get("title", task["question"]),
                owner,
                task.get("due") or "미정",
                ", ".join(task.get("depends_on", [])) or "없음",
                "제출 준비" if task.get("required_for_submission") else "보완",
                task["status"],
            )
        )
    return rows


def rebase(text, source, output):
    def replace(match):
        href = match.group(1)
        if re.match(r"^[a-zA-Z][a-zA-Z0-9+.-]*:", href):
            return match.group(0)
        path, separator, anchor = href.partition("#")
        target = ((ROOT / source).parent / path).resolve() if path else ROOT / output
        relative = os.path.relpath(target, (ROOT / output).parent).replace("\\", "/")
        return (
            "]("
            + relative.replace(" ", "%20")
            + (separator + anchor if anchor else "")
            + ")"
        )

    return LINK.sub(replace, text)


def render_document(record, source, output):
    lines = header(record["title"], [source], output)
    if output == "docs/step1/기획서.md" and record.get("submission_sections"):
        lines.append(
            rebase(
                record.get("submission_preamble_markdown", record["preamble_markdown"]),
                source,
                output,
            )
        )
        sections = record["submission_sections"]
    else:
        lines.append(rebase(record["preamble_markdown"], source, output))
        sections = record["sections"]
    for section in sections:
        lines.extend(
            [
                "#" * section["level"] + " " + section["heading"],
                rebase(section["content_markdown"], source, output),
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


