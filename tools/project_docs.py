def validate_result(record, label):
    require(
        record,
        [
            "summary",
            "claims",
            "evidence",
            "verification",
            "uncertainties",
            "decision_requests",
        ],
        label,
    )
    if not isinstance(record["summary"], str):
        raise TypeError(f"{label}: summary must be text")
    for key in (
        "claims",
        "evidence",
        "verification",
        "uncertainties",
        "decision_requests",
    ):
        if not isinstance(record[key], list):
            raise TypeError(f"{label}: {key} must be an array")
    evidence_ids = set()
    for evidence in record["evidence"]:
        require(evidence, ["id"], label)
        if evidence["id"] in evidence_ids or not (
            evidence.get("path") or evidence.get("url")
        ):
            raise ValueError(f"{label}: evidence needs a unique ID and a path or URL")
        if evidence.get("path") and not (ROOT / evidence["path"]).is_file():
            raise ValueError(f"{label}: missing evidence file {evidence['path']}")
        evidence_ids.add(evidence["id"])
    for claim in record["claims"]:
        require(claim, ["id", "text", "status", "evidence_ids"], label)
        if not set(claim["evidence_ids"]) <= evidence_ids:
            raise ValueError(f"{label}: claim references unknown evidence")
    for check in record["verification"]:
        require(check, ["criterion", "verdict", "evidence_ids"], label)
        if (
            check["verdict"] not in ("pass", "fail", "inconclusive")
            or not set(check["evidence_ids"]) <= evidence_ids
        ):
            raise ValueError(f"{label}: invalid verification or evidence references")


def validate_historical_task_result(path, record):
    """Check the exact inactive TASK-032 archived blob in its legacy format."""
    if record["id"] != "TASK-032":
        return False
    state = read_json(STATE)
    if record["id"] in state.get("active_task_ids", []):
        return False
    closeout = read_json(state["task_closeout_ref"])
    entries = [item for item in closeout["entries"] if item["id"] == record["id"]]
    if len(entries) != 1:
        raise ValueError("TASK-032 missing unique closeout")
    source = entries[0]["source"]
    actual = subprocess.check_output(
        ["git", "hash-object", f"--path={path}", str(ROOT / path)],
        cwd=ROOT, text=True, encoding="ascii"
    ).strip()
    if source["path"] != path or source["blob_sha"] != actual or record["status"] != "검토 중":
        raise ValueError("TASK-032 historical record changed; explicit migration required")
    result = record["result"]
    require(result, ["summary", "evidence", "verification", "uncertainties", "decision_requests"], path)
    evidence_ids = {item["id"] for item in result["evidence"]}
    if len(evidence_ids) != len(result["evidence"]):
        raise ValueError("duplicate historical evidence")
    for evidence in result["evidence"]:
        if not (evidence.get("path") or evidence.get("url")):
            raise ValueError("missing historical evidence reference")
        if evidence.get("path") and not (ROOT / evidence["path"]).is_file():
            raise ValueError(f"missing historical evidence file {evidence['path']}")
    for check in result["verification"]:
        if check["verdict"] not in ("pass", "fail", "pending", "inconclusive"):
            raise ValueError("invalid historical verdict")
        if not set(check.get("evidence_ids", [])) <= evidence_ids:
            raise ValueError("unknown historical evidence")
        if check["verdict"] == "pending" and not check.get("reason"):
            raise ValueError("unexplained historical pending verdict")
    return True


def validate(sources):
    ids = set()
    for path, record in sources.items():
        require(record, ["schema_version", "id", "kind", "status"], path)
        if record["schema_version"] != 1 or record["id"] in ids:
            raise ValueError(f"{path}: invalid version or duplicate ID")
        ids.add(record["id"])
        if record["kind"] == "task":
            require(
                record,
                [
                    "question",
                    "goal",
                    "inputs",
                    "scope",
                    "outputs",
                    "acceptance",
                    "verification",
                    "result",
                ],
                path,
            )
            if record["status"] not in ("할 일", "진행 중", "검토 중", "완료", "막힘"):
                raise ValueError(f"{path}: invalid task status")
            traceability = record.get("traceability")
            if traceability is not None:
                if not isinstance(traceability, dict):
                    raise TypeError(f"{path}: traceability must be an object")
                for key in (
                    "intent_refs",
                    "design_refs",
                    "requirement_refs",
                    "evaluation_refs",
                ):
                    if key in traceability and not isinstance(traceability[key], list):
                        raise TypeError(f"{path}: traceability.{key} must be an array")
            validation_plan = record.get("validation_plan")
            if validation_plan is not None:
                if not isinstance(validation_plan, dict):
                    raise TypeError(f"{path}: validation_plan must be an object or null")
                require(
                    validation_plan,
                    ["question", "observables", "success_condition", "unknown_condition"],
                    f"{path}.validation_plan",
                )
                if not isinstance(validation_plan["observables"], list):
                    raise TypeError(f"{path}: validation_plan.observables must be an array")
            if record["status"] == "완료":
                result = record["result"]
                if (
                    not result
                    or not result.get("verification")
                    or not result.get("evidence")
                ):
                    raise ValueError(
                        f"{path}: completed task needs verification and evidence"
                    )
            if record["result"] is not None and not validate_historical_task_result(path, record):
                validate_result(record["result"], path)
        if record["kind"] == "run":
            require(
                record,
                ["case_id", "input", "plan", "steps", "claims", "evidence"],
                path,
            )
        if record["kind"] == "decision" and record["status"] == "확정":
            require(record, ["decided_by", "authority_ref"], path)
            if not (ROOT / record["authority_ref"]).is_file():
                raise ValueError(
                    f"{path}: missing human authority reference {record['authority_ref']}"
                )
        if record["kind"] == "evaluation":
            require(record, ["case_id", "run_path", "checks", "verdict"], path)
            if (
                record["verdict"] not in ("pass", "fail", "inconclusive")
                or not record["checks"]
            ):
                raise ValueError(f"{path}: invalid evaluation verdict or empty checks")
            for check in record["checks"]:
                require(check, ["criterion", "verdict", "evidence"], path)
                if (
                    check["verdict"] not in ("pass", "fail", "inconclusive")
                    or not check["evidence"]
                ):
                    raise ValueError(f"{path}: check needs a verdict and evidence")
            if record["verdict"] == "pass" and any(
                check["verdict"] != "pass" for check in record["checks"]
            ):
                raise ValueError(f"{path}: passing evaluation has unresolved checks")
            if not (ROOT / record["run_path"]).is_file():
                raise ValueError(f"{path}: missing run evidence")
        for reference in record.get("references", []):
            target = reference.get("path")
            # Historical research may reference local-only original material.
            if target and not (ROOT / target).exists() and not record.get("provenance"):
                raise ValueError(f"{path}: missing reference {target}")

    if WBS in sources:
        wbs = sources[WBS]
        require(wbs, ["items"], WBS)
        wbs_items = {item["id"]: item for item in wbs["items"]}
        if len(wbs_items) != len(wbs["items"]):
            raise ValueError(f"{WBS}: duplicate work item ID")
        owners = {member["id"] for member in wbs.get("team", [])}
        subtask_ids = set()
        graph = {}
        for item in wbs["items"]:
            require(
                item,
                ["id", "start", "end", "depends_on", "requirements"],
                f"{WBS}.{item.get('id', '?')}",
            )
            if not wbs["period"]["start"] <= item["start"] <= item["end"] <= wbs["period"]["end"]:
                raise ValueError(f"{WBS}: {item['id']} invalid work dates")
            if owners and item["owner"] not in owners:
                raise ValueError(f"{WBS}: {item['id']} unknown owner")
            graph[item["id"]] = item["depends_on"] + item.get("completion_dependencies", [])
            for predecessor_id in item["depends_on"]:
                if predecessor_id not in wbs_items:
                    raise ValueError(
                        f"{WBS}: {item['id']} references unknown dependency {predecessor_id}"
                    )
                predecessor = wbs_items[predecessor_id]
                if item["start"] < predecessor["end"]:
                    raise ValueError(
                        f"{WBS}: {item['id']} starts {item['start']} before "
                        f"{predecessor_id} ends {predecessor['end']}"
                    )
            for dependency in item.get("completion_dependencies", []):
                if dependency not in wbs_items or wbs_items[dependency]["end"] > item["end"]:
                    raise ValueError(f"{WBS}: {item['id']} invalid completion dependency {dependency}")
            children = item.get("subtasks", [])
            if not children and not 1 <= item["estimate_workdays"] <= 3:
                raise ValueError(f"{WBS}: {item['id']} needs 1-3 day subtasks")
            if children and sum(child["estimate_workdays"] for child in children) != item["estimate_workdays"]:
                raise ValueError(f"{WBS}: {item['id']} subtask effort mismatch")
            for child in children:
                require(child, ["id", "owner", "start", "end", "estimate_workdays", "output", "done_when"], item["id"])
                if child["id"] in subtask_ids or child["id"] in wbs_items:
                    raise ValueError(f"{WBS}: duplicate subtask {child['id']}")
                subtask_ids.add(child["id"])
                if not item["start"] <= child["start"] <= child["end"] <= item["end"]:
                    raise ValueError(f"{WBS}: {child['id']} outside parent dates")
                if not 1 <= child["estimate_workdays"] <= 3 or (owners and child["owner"] not in owners):
                    raise ValueError(f"{WBS}: {child['id']} invalid effort or owner")
            actual = item.get("actual", {})
            progress = actual.get("progress_percent")
            if progress is not None and (not isinstance(progress, (float, int)) or not 0 <= progress <= 100):
                raise ValueError(f"{WBS}: {item['id']} invalid progress")
            if (progress is not None or actual.get("start") or actual.get("end")) and not actual.get("evidence_refs"):
                raise ValueError(f"{WBS}: {item['id']} actual progress needs evidence")
        tuple(TopologicalSorter(graph).static_order())
        milestone_ids = {m["id"] for m in wbs["milestones"]}
        if len(milestone_ids) != len(wbs["milestones"]):
            raise ValueError(f"{WBS}: duplicate milestone ID")
        for deliverable in wbs.get("deliverable_schedule", []):
            if deliverable["id"] not in milestone_ids or not set(deliverable["wbs_refs"]) <= wbs_items.keys():
                raise ValueError(f"{WBS}: invalid deliverable mapping {deliverable['id']}")


def validate_lesson_design_sources():
    """Route the versioned lesson design bundle to its own pinned-source model.

    Unlike task/state envelopes, this bundle includes JSON Schema, replay
    evidence, versioned contracts and history. Never silently skip an unknown
    file: the adopted manifest and explicit adoption metadata cover the folder.
    The separate design projection checker verifies rendered contents.
    """
    bundle = ARTIFACTS / "design/lesson-registration-20261124"
    manifest_path = ROOT / "docs/design/lesson-registration/MANIFEST.json"
    if not bundle.is_dir():
        return set()
    manifest = read_json(manifest_path.relative_to(ROOT))
    adoption_path = bundle / "adoption-20261125.json"
    adoption = read_json(adoption_path.relative_to(ROOT))
    if (adoption.get("canonical_commit") != manifest.get("source_commit")
            or adoption.get("id") != "LR-ADOPT-20261125"
            or adoption.get("authority") != "R01"):
        raise ValueError("lesson adoption and review snapshot differ")
    inventory = {entry["path"]: entry["sha"] for entry in manifest["inventory"]}
    actual = {path.relative_to(ROOT).as_posix() for path in bundle.rglob("*") if path.is_file()}
    adoption_rel = adoption_path.relative_to(ROOT).as_posix()
    if len(inventory) != len(manifest["inventory"]) or actual != set(inventory) | {adoption_rel}:
        raise ValueError("lesson design source inventory differs; update design review and adoption explicitly")
    for path, expected in inventory.items():
        blob = subprocess.check_output(
            ["git", "hash-object", f"--path={path}", str(ROOT / path)],
            cwd=ROOT, text=True, encoding="ascii"
        ).strip()
        if blob != expected:
            raise ValueError(f"lesson design source differs from adopted snapshot: {path}")
        if path.endswith(".json"):
            read_json(path)
    prefix = bundle.relative_to(ROOT).as_posix() + "/"
    for name in adoption.get("current_refs", []):
        if prefix + name not in inventory:
            raise ValueError(f"missing adopted design reference {name}")
    return {ROOT / path for path in actual if path.endswith(".json")}


