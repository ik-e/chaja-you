def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when source validation or a projection is stale.",
    )
    args = parser.parse_args()
    try:
        outputs = build()  # Validate every source before writing any projection.
    except (ValueError, KeyError, TypeError, OSError) as error:
        print(f"Invalid source: {error}", file=sys.stderr)
        return 1
    stale = []
    for path, text in outputs.items():
        target = ROOT / path
        if target.is_file() and target.read_text(encoding="utf-8") == text:
            continue
        stale.append(path)
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            temporary = target.with_suffix(target.suffix + ".tmp")
            temporary.write_text(text, encoding="utf-8", newline="\n")
            temporary.replace(target)
    if args.check and stale:
        print("Stale projections:\n" + "\n".join(stale), file=sys.stderr)
        for path in stale[:3]:
            target = ROOT / path
            existing = target.read_text(encoding="utf-8").splitlines(keepends=True) if target.exists() else []
            expected = outputs[path].splitlines(keepends=True)
            print("".join(list(difflib.unified_diff(existing, expected, fromfile=f"current/{path}", tofile=f"expected/{path}"))[:100]), file=sys.stderr)
        return 1
    print(
        f"{len(outputs)} projections verified; {len(stale)} updated."
        if not args.check
        else f"{len(outputs)} projections current."
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
